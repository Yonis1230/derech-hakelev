// Static articles using the existing dog-site shell. No client-side framework.
// --preview includes drafts ONLY under artifacts/preview/article-pages.
// Default generation includes approved articles with an actual publication date.
'use strict';

const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const crypto = require('node:crypto');
const articles = require('./articles-content.cjs');
const articleRoute = require('./article-routes.cjs');
const {renderInline, plainInline} = require('./article-inline.cjs');
const {articleDocument, searchIndex} = require('./article-search-model.cjs');
const commentsConfig = require('./article-comments-config.cjs');
const community = require('./whatsapp-community.cjs');
const root = path.resolve(__dirname, '..');
const docs = path.join(root, 'docs');
const preview = process.argv.includes('--preview');
const check = process.argv.includes('--check');
const outputRoot = preview ? path.join(root, 'artifacts/preview/article-pages') : docs;
const origin = 'https://derech-hakelev.com';
const marker = '<!-- Generated by tools/build-article-pages.cjs. -->';
const escape = value => String(value).replace(/[&<>"']/g, c => ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
const home = fs.readFileSync(path.join(docs, 'index.html'), 'utf8');
const sourceContext = vm.createContext({window: {}});
for (const filename of ['catalog.js', 'media.js']) {
 vm.runInContext(fs.readFileSync(path.join(docs, filename), 'utf8'), sourceContext, {filename, timeout: 1000});
}
const gallery = sourceContext.window.DERECH_HOME_IMAGES;
const media = sourceContext.window.DERECH_MEDIA;
const selected = articles.filter(article => preview || article.status === 'approved');
const slugs = new Set();
let changes = 0;
if (commentsConfig.enabled && !/^[a-zA-Z0-9][a-zA-Z0-9_-]{1,99}$/.test(commentsConfig.siteId || '')) throw new Error('Comments need the real public GraphComment shortname.');

// Authored prose can link to published articles and existing catalog pages.
// Product destinations come from the same catalog and route as the product
// builder; an arbitrary file under products/ cannot add itself to the allowlist.
const inlineLinks = new Set(articles.filter(article => article.status === 'approved').map(article => '/' + articleRoute(article)));
inlineLinks.add('/pages/games/');
const catalog = sourceContext.window.DERECH_CATALOG;
if (!Array.isArray(catalog) || !catalog.length) throw new Error('Missing product catalog.');
const productIds = new Set();
for (const product of catalog) {
 if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(product.id) || productIds.has(product.id)) throw new Error('Invalid or duplicate catalog product ID.');
 productIds.add(product.id);
 const route = '/pages/games/products/' + product.id + '/';
 const file = path.join(docs, route.slice(1), 'index.html');
 if (!fs.existsSync(file) || !fs.statSync(file).isFile()) continue;
 const html = fs.readFileSync(file, 'utf8');
 if (!html.includes('<!-- Generated by tools/build-product-pages.cjs; edit docs/catalog.js, then rebuild. -->') || !html.includes('<link rel="canonical" href="' + origin + route + '">')) throw new Error('Unexpected catalog product page: ' + route);
 inlineLinks.add(route);
}
const inline = value => renderInline(value, inlineLinks);

// Ordered text/list blocks keep authored lists in place without allowing raw HTML.
function sectionBlocks(section) {
 return section.blocks || (section.paragraphs || []).map(text => ({type: 'paragraph', text}));
}

function blockText(block) {
 return block.type === 'list' ? block.items.join(' ') : block.text;
}

function renderBlock(block) {
 if (block.type === 'list') return '<ul>' + block.items.map(item => '<li' + anchor(item) + '>' + inline(item.raw) + '</li>').join('') + '</ul>';
 if (block.type === 'subheading') return '<h3' + anchor(block) + '>' + inline(block.raw) + '</h3>';
 return '<p' + anchor(block, block.type === 'note' ? 'article-note' : '') + '>' + inline(block.raw) + '</p>';
}

function anchor(entry, extraClass = '') {
 return ' id="' + entry.id + '" class="article-anchor' + (extraClass ? ' ' + extraClass : '') + '" tabindex="-1"';
}

for (const article of articles) {
 if (!/^[a-z]+(?:-[a-z]+)*$/.test(article.slug) || slugs.has(article.slug)) throw new Error('Invalid or duplicate article slug.');
 slugs.add(article.slug);
 articleRoute(article);
 if (article.seoTitle !== undefined && (typeof article.seoTitle !== 'string' || !article.seoTitle.trim())) throw new Error('Invalid SEO title.');
 if (!['draft', 'approved'].includes(article.status) || !article.title || !article.description || !article.intro || !article.category || !article.sections?.length) throw new Error('Incomplete article: ' + article.slug);
 if (article.status === 'approved' && (!/^\d{4}-\d{2}-\d{2}$/.test(article.publishedOn || '') || !Number.isFinite(Date.parse(article.publishedOn)) || article.publishedOn > new Date().toISOString().slice(0, 10))) throw new Error('Approved articles need a real publication date: ' + article.slug);
 if (article.openingParagraphs && (!Array.isArray(article.openingParagraphs) || article.openingParagraphs.some(paragraph => typeof paragraph !== 'string' || !paragraph.trim() || /[<>]/.test(paragraph)))) throw new Error('Invalid opening paragraphs.');
 if (article.image) {
  const image = media[article.image.source];
  const dedicatedImage = new RegExp('^assets/images/articles/' + article.slug + '\\.(?:jpe?g|webp|png)$').test(article.image.source);
  if ((!gallery.includes(article.image.source) && !dedicatedImage) || !article.image.alt?.trim() || !image?.srcset || !(image.width > 0) || !(image.height > 0)) throw new Error('Article image must be a gallery or dedicated article photograph with alternative text.');
  for (const asset of [article.image.source, image.src, ...image.srcset.split(',').map(candidate => candidate.trim().split(/\s+/)[0])]) {
   const file = path.resolve(docs, asset);
   if (!file.startsWith(docs + path.sep) || !fs.existsSync(file) || !fs.statSync(file).isFile()) throw new Error('Missing or unsafe article image: ' + asset);
  }
 }
 if (article.references) {
  const urls = new Set();
  for (const reference of article.references) {
   if (!reference.title || !reference.description) throw new Error('Incomplete research reference.');
   if (!reference.url) continue; // A printed book can be cited without a web link.
   const url = new URL(reference.url);
   if (url.protocol !== 'https:' || urls.has(url.href)) throw new Error('Invalid or duplicate research link.');
   urls.add(url.href);
  }
 }
 if (article.next && (!article.next.heading || !article.next.description || !article.next.label || !/^(?:index\.html#[a-z]+|pages\/[a-z]+\/)$/.test(article.next.path))) throw new Error('Invalid article continuation.');
 for (const section of article.sections) {
  const blocks = sectionBlocks(section);
  if (!section.heading || !Array.isArray(blocks) || !blocks.length || (section.blocks && section.paragraphs)) throw new Error('Incomplete article section.');
  for (const block of blocks) {
   if (block.type === 'list') {
    if (!Array.isArray(block.items) || !block.items.length || block.items.some(item => typeof item !== 'string' || !item.trim())) throw new Error('Invalid article list.');
    block.items.forEach(inline);
   } else if (['paragraph', 'note', 'subheading'].includes(block.type) && typeof block.text === 'string' && block.text.trim()) {
    inline(block.text);
   } else throw new Error('Invalid article text block.');
  }
 }
 if (article.status === 'draft' && fs.existsSync(path.join(docs, articleRoute(article), 'index.html'))) throw new Error('A draft has a public output. Review and remove that output before continuing.');
}

const generatedSearchIndex = searchIndex(articles);
const searchIndexVersion = crypto.createHash('sha256').update(JSON.stringify(generatedSearchIndex)).digest('hex').slice(0, 12);

function shared(tag, base, route) {
 const fragment = home.match(new RegExp('<' + tag + '\\b[\\s\\S]*?<\\/' + tag + '>'))?.[0];
 if (!fragment) throw new Error('Missing shared ' + tag);
 const rebased = fragment.replace(/\b(href|src)="(?![a-z][a-z\d+.-]*:|\/\/|#)([^"]+)"/gi, (_, attribute, url) => attribute + '="' + base + url + '"');
 if (tag !== 'header') return rebased;
 const link = '<a href="' + base + 'pages/articles/">מאמרים</a>';
 const activeLink = link.replace('>מאמרים', ' aria-current="' + (route === 'pages/articles/' ? 'page' : 'location') + '">מאמרים');
 return rebased.includes(link) ? rebased.replace(link, activeLink) : rebased.replace('</nav>', activeLink + '\n</nav>');
}

