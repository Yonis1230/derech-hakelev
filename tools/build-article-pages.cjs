// Static articles using the existing dog-site shell. No client-side framework.
// --preview includes drafts ONLY under artifacts/preview/article-pages.
// Default generation includes approved articles with an actual publication date.
'use strict';

const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const articles = require('./articles-content.cjs');
const root = path.resolve(__dirname, '..');
const docs = path.join(root, 'docs');
const preview = process.argv.includes('--preview');
const check = process.argv.includes('--check');
const outputRoot = preview ? path.join(root, 'artifacts/preview/article-pages') : docs;
const origin = 'https://derech-hakelev.com';
const marker = '<!-- Generated by tools/build-article-pages.cjs. -->';
const escape = value => String(value).replace(/[&<>"']/g, c => ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
const home = fs.readFileSync(path.join(docs, 'index.html'), 'utf8');
const sourceContext = vm.createContext({window: {}});
for (const filename of ['catalog.js', 'media.js']) {
 vm.runInContext(fs.readFileSync(path.join(docs, filename), 'utf8'), sourceContext, {filename, timeout: 1000});
}
const gallery = sourceContext.window.DERECH_HOME_IMAGES;
const media = sourceContext.window.DERECH_MEDIA;
const selected = articles.filter(article => preview || article.status === 'approved');
const slugs = new Set();
let changes = 0;

// Preserve authored bold text without accepting arbitrary inline HTML.
// The older game article also includes a small set of local product links.
function inline(value) {
 const productLink = /(<a href="\.\.\/\.\.\/\.\.\/pages\/games\/products\/[a-z]+\/">[^<>]+<\/a>)/g;
 function emphasis(text) {
  return text.split(/(\*\*[^*]+\*\*|\*[^*]+\*)/g).map(part => {
   if (/^\*\*[^*]+\*\*$/.test(part)) return '<strong>' + escape(part.slice(2, -2)) + '</strong>';
   if (/^\*[^*]+\*$/.test(part)) return '<em>' + escape(part.slice(1, -1)) + '</em>';
   return escape(part);
  }).join('');
 }
 return String(value).split(productLink).map(part => {
  const link = part.match(/^<a href="(\.\.\/\.\.\/\.\.\/pages\/games\/products\/[a-z]+\/)">([^<>]+)<\/a>$/);
  if (link) return '<a href="' + link[1] + '">' + emphasis(link[2]) + '</a>';
  if (/[<>]/.test(part)) throw new Error('Unexpected inline article markup.');
  return emphasis(part);
 }).join('');
}

for (const article of articles) {
 if (!/^[a-z]+(?:-[a-z]+)*$/.test(article.slug) || slugs.has(article.slug)) throw new Error('Invalid or duplicate article slug.');
 slugs.add(article.slug);
 if (!['draft', 'approved'].includes(article.status) || !article.title || !article.description || !article.intro || !article.category || !article.sections?.length) throw new Error('Incomplete article: ' + article.slug);
 if (article.status === 'approved' && (!/^\d{4}-\d{2}-\d{2}$/.test(article.publishedOn || '') || !Number.isFinite(Date.parse(article.publishedOn)) || article.publishedOn > new Date().toISOString().slice(0, 10))) throw new Error('Approved articles need a real publication date: ' + article.slug);
 if (article.openingParagraphs && (!Array.isArray(article.openingParagraphs) || article.openingParagraphs.some(paragraph => typeof paragraph !== 'string' || !paragraph.trim() || /[<>]/.test(paragraph)))) throw new Error('Invalid opening paragraphs.');
 if (article.image) {
  const image = media[article.image.source];
  if (!gallery.includes(article.image.source) || !article.image.alt?.trim() || !image?.srcset || !(image.width > 0) || !(image.height > 0)) throw new Error('Article image must reuse an existing gallery photograph with alternative text.');
  for (const asset of [article.image.source, image.src, ...image.srcset.split(',').map(candidate => candidate.trim().split(/\s+/)[0])]) {
   const file = path.resolve(docs, asset);
   if (!file.startsWith(docs + path.sep) || !fs.existsSync(file) || !fs.statSync(file).isFile()) throw new Error('Missing or unsafe article image: ' + asset);
  }
 }
 if (article.references) {
  const urls = new Set();
  for (const reference of article.references) {
   if (!reference.title || !reference.description) throw new Error('Incomplete research reference.');
   if (!reference.url) continue; // A printed book can be cited without a web link.
   const url = new URL(reference.url);
   if (url.protocol !== 'https:' || urls.has(url.href)) throw new Error('Invalid or duplicate research link.');
   urls.add(url.href);
  }
 }
 if (article.next && (!article.next.heading || !article.next.description || !article.next.label || !/^(?:index\.html#[a-z]+|pages\/[a-z]+\/)$/.test(article.next.path))) throw new Error('Invalid article continuation.');
 for (const section of article.sections) {
  if (!section.heading || !section.paragraphs?.length) throw new Error('Incomplete article section.');
  for (const paragraph of section.paragraphs) {
   inline(paragraph);
  }
 }
 if (article.status === 'draft' && fs.existsSync(path.join(docs, 'pages/articles', article.slug, 'index.html'))) throw new Error('A draft has a public output. Review and remove that output before continuing.');
}

function shared(tag, base, route) {
 const fragment = home.match(new RegExp('<' + tag + '\\b[\\s\\S]*?<\\/' + tag + '>'))?.[0];
 if (!fragment) throw new Error('Missing shared ' + tag);
 const rebased = fragment.replace(/\b(href|src)="(?![a-z][a-z\d+.-]*:|\/\/|#)([^"]+)"/gi, (_, attribute, url) => attribute + '="' + base + url + '"');
 if (tag !== 'header') return rebased;
 const link = '<a href="' + base + 'pages/articles/">מאמרים</a>';
 const activeLink = link.replace('>מאמרים', ' aria-current="' + (route === 'pages/articles/' ? 'page' : 'location') + '">מאמרים');
 return rebased.includes(link) ? rebased.replace(link, activeLink) : rebased.replace('</nav>', activeLink + '\n</nav>');
}

function layout({title, description, route, base, content, schema = '', image}) {
 const canonical = origin + '/' + route;
 const socialImage = image ? media[image.source].src : 'assets/optimized/brand/logo-128.webp';
 return [
  marker, '<!doctype html>',
  '<html lang="he" dir="rtl"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">',
  '<title>' + escape(title) + ' | דרך הכלב</title>',
  '<meta name="description" content="' + escape(description) + '">',
  preview ? '<meta name="robots" content="noindex, nofollow">' : '',
  '<link rel="canonical" href="' + canonical + '">',
  '<meta property="og:title" content="' + escape(title) + ' | דרך הכלב"><meta property="og:description" content="' + escape(description) + '"><meta property="og:url" content="' + canonical + '"><meta property="og:type" content="' + (route !== 'pages/articles/' ? 'article' : 'website') + '"><meta property="og:locale" content="he_IL"><meta property="og:image" content="' + origin + '/' + socialImage + '">',
  image ? '<meta property="og:image:alt" content="' + escape(image.alt) + '">' : '',
  '<link rel="icon" href="' + base + 'assets/optimized/favicon-32.png"><link rel="stylesheet" href="' + base + 'styles.css?v=20261102-articles">',
  schema,
  '<script src="' + base + 'scripts.js?v=20261031-measurement" defer></script><script src="' + base + 'accessibility.js?v=20261031-accessibility-menu" defer></script><script src="' + base + 'analytics.js?v=20261031-measurement" defer></script><script src="' + base + 'measurement.js?v=20261031-ga4" defer></script>',
  '</head><body data-base="' + base + '" data-page="article"><a class="skip-link" href="#main">דלגו לתוכן</a>' + shared('header', base, route),
  content, shared('footer', base), '</body></html>', ''
 ].join('\n');
}

function write(route, html) {
 const file = path.join(outputRoot, route, 'index.html');
 const existing = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
 if (existing && !existing.startsWith(marker)) throw new Error('Refusing to overwrite a hand-edited page: ' + file);
 if (existing === html) return;
 changes++;
 if (!check) {
  fs.mkdirSync(path.dirname(file), {recursive: true});
  fs.writeFileSync(file, html);
 }
}

function previewNote() {
 return preview ? '<p class="article-preview-note" role="note">תצוגה מקומית לבדיקה · המאמר טרם אושר או פורסם באתר</p>' : '';
}

function photograph(article, base, thumbnail = false) {
 if (!article.image) return '';
 const entry = media[article.image.source];
 const srcset = entry.srcset.split(',').map(candidate => base + candidate.trim()).join(', ');
 return '<img class="' + (thumbnail ? 'article-thumbnail' : 'article-photo') + '" src="' + base + entry.src + '" srcset="' + srcset + '" sizes="' + (thumbnail ? '(max-width: 760px) calc(100vw - 36px), 250px' : '(max-width: 760px) calc(100vw - 36px), 760px') + '" width="' + entry.width + '" height="' + entry.height + '" alt="' + (thumbnail ? '' : escape(article.image.alt)) + '" ' + (thumbnail ? 'loading="lazy"' : 'fetchpriority="high"') + ' decoding="async">';
}

if (selected.length) {
 const cards = selected.map(article => [
  '<article class="article-list-item' + (article.image ? ' has-image' : '') + '">' + photograph(article, '../../', true) + '<div class="article-card-copy"><span class="eyebrow">' + escape(article.category) + '</span>',
  '<h2><a href="' + article.slug + '/">' + escape(article.title) + '</a></h2><p>' + escape(article.description) + '</p>',
  '<a class="text-link" href="' + article.slug + '/">לקריאת המאמר<span class="sr-only">: ' + escape(article.title) + '</span> <span aria-hidden="true">←</span></a></div></article>'
 ].join('')).join('\n');
 write('pages/articles', layout({
  title: 'מאמרים ורעיונות למפגש',
  description: 'מאמרים על טיפול רגשי בעזרת כלבים, קשר, משחק והתנסות בתוך המפגש.',
  route: 'pages/articles/', base: '../../',
  content: '<main id="main" class="articles-page">' + previewNote() + '<div class="articles-intro"><span class="eyebrow">לקרוא, לחשוב, לנסות</span><h1>מאמרים ורעיונות למפגש</h1><p>על טיפול רגשי בעזרת כלבים, על קשר ועל משחק. מחשבות מתוך המפגש ורעיונות שאפשר לקחת איתנו להמשך.</p></div><div class="articles-list">' + cards + '</div></main>'
 }));
}

for (const article of selected) {
 const route = 'pages/articles/' + article.slug + '/';
 const body = article.sections.map(section => '<section><h2>' + escape(section.heading) + '</h2>' + section.paragraphs.map(paragraph => '<p>' + inline(paragraph) + '</p>').join('') + '</section>').join('\n');
 const opening = (article.openingParagraphs || []).map(paragraph => '<p>' + inline(paragraph) + '</p>').join('');
 const words = [article.intro, ...(article.openingParagraphs || []), ...article.sections.flatMap(section => [section.heading, ...section.paragraphs])].join(' ').replace(/<[^>]+>/g, '').split(/\s+/).length;
 const date = article.status === 'approved' ? '<span>יוני סויסה · <time datetime="' + article.publishedOn + '">' + article.publishedOn.split('-').reverse().join('.') + '</time></span>' : '<span>' + (article.author ? escape(article.author) + ' · ' : '') + 'טיוטה לבדיקה</span>';
 const references = article.references?.length ? '<section class="article-references" aria-labelledby="research-sources"><h2 id="research-sources">' + escape(article.referencesTitle || 'מקורות ומחקרים להרחבה') + '</h2><ul>' + article.references.map(reference => '<li><strong><bdi dir="ltr">' + escape(reference.title) + '</bdi></strong>' + (reference.workTitle ? '<p><em><bdi dir="ltr">' + escape(reference.workTitle) + '</bdi></em></p>' : '') + '<p>' + escape(reference.description) + '</p>' + (reference.note ? '<p class="research-note">' + escape(reference.note) + '</p>' : '') + (reference.url ? '<a href="' + escape(reference.url) + '">' + escape(reference.linkLabel || 'למחקר') + '<span class="sr-only">: ' + escape(reference.title) + '</span> <span aria-hidden="true">←</span></a>' : '') + '</li>').join('') + '</ul></section>' : '';
 const next = article.next || {heading: 'רוצים להכיר את המשחקים?', description: 'בקטלוג אפשר לראות מה יש בכל מארז, לאילו גילאים הוא מתאים ואיך משחקים בו.', label: 'לכל המשחקים והכלים', path: 'pages/games/'};
 const schema = !preview ? '<script type="application/ld+json">' + JSON.stringify({
  '@context': 'https://schema.org', '@type': 'Article', headline: article.title, description: article.description,
  inLanguage: 'he', mainEntityOfPage: origin + '/' + route, datePublished: article.publishedOn,
  ...(article.image ? {image: origin + '/' + media[article.image.source].src} : {}),
  author: {'@type': 'Person', '@id': origin + '/#yoni', name: 'יוני סויסה'},
  publisher: {'@type': 'Organization', '@id': origin + '/#organization', name: 'דרך הכלב', url: origin + '/'}
 }).replace(/</g, '\\u003c') + '</script>' : '';
 write(route, layout({
  title: article.title, description: article.description, route, base: '../../../', schema, image: article.image,
  content: '<main id="main" class="reading-page">' + previewNote() +
   '<nav class="article-breadcrumbs" aria-label="מיקום באתר"><a href="../">כל המאמרים</a><span aria-hidden="true">/</span><span aria-current="page">' + escape(article.title) + '</span></nav>' +
   '<article><header class="article-heading"><span class="eyebrow">' + escape(article.category) + '</span><h1>' + escape(article.title) + '</h1>' +
   '<div class="article-meta">' + date + '<span>כ־' + Math.max(1, Math.ceil(words / 170)) + ' דקות קריאה</span></div></header>' +
   (article.image ? '<figure class="article-hero">' + photograph(article, '../../../') + '</figure>' : '') +
   '<div class="article-body"><p class="article-intro">' + inline(article.intro) + '</p>' + opening + body + '</div>' + references + '</article><aside class="article-next" aria-label="להמשך"><h2>' + escape(next.heading) + '</h2><p>' + escape(next.description) + '</p><a class="button" href="../../../' + next.path + '">' + escape(next.label) + ' <span aria-hidden="true">←</span></a></aside></main>'
 }));
}

console.log((check ? 'Checked' : 'Generated') + ' ' + selected.length + ' article(s) ' + (preview ? 'in local preview only' : 'approved for public output') + '; ' + changes + ' file change(s).');
if (check && changes) process.exitCode = 1;
