function writeSearchIndex() {
 const file = path.join(outputRoot, 'article-search-index.js');
 const prefix = '// Generated by tools/build-article-pages.cjs.\n';
 const content = prefix + 'window.DERECH_ARTICLE_SEARCH = ' + JSON.stringify(generatedSearchIndex).replace(/</g, '\\u003c') + ';\n';
 const existing = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
 if (existing && !existing.startsWith(prefix)) throw new Error('Refusing to overwrite a hand-edited search index.');
 if (existing === content) return;
 changes++;
 if (!check) {
  fs.mkdirSync(outputRoot, {recursive: true});
  fs.writeFileSync(file, content);
 }
}

