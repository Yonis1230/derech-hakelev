/* Public Clarity project ID. This file is shared by both website pages. */
(() => {
 'use strict';
 const projectId = 'ywqq9e8u1f';
 const storageKey = 'derech-analytics-consent-v1';
 const production = ['derech-hakelev.com', 'www.derech-hakelev.com'].includes(location.hostname);
 let consent = null;
 let started = false;
 try { consent = localStorage.getItem(storageKey); } catch { /* Storage may be disabled. */ }

 function start() {
  // Local previews never send visitor data to the live project.
  if (!production || started || consent !== 'granted') return;
  started = true;
  window.clarity = window.clarity || function () {
   (window.clarity.q = window.clarity.q || []).push(arguments);
  };
  window.clarity('consentv2', {analytics_Storage: 'granted', ad_Storage: 'denied'});
  window.clarity('set', 'site_page', document.getElementById('catalog') ? 'games' : 'home');
  const script = document.createElement('script');
  script.async = true;
  script.src = 'https://www.clarity.ms/tag/' + projectId;
  document.head.append(script);
 }

 function event(name) {
  if (started && consent === 'granted') window.clarity('event', name);
 }

 document.addEventListener('DOMContentLoaded', () => {
  const panel = document.createElement('section');
  panel.className = 'analytics-consent';
  panel.setAttribute('aria-label', 'העדפות מדידה');
  panel.innerHTML = '<p><strong>עוזרים לנו לשפר את האתר?</strong> באישורכם נשתמש ב־Microsoft Clarity למדידת שימוש, מפות חום והקלטות של האינטראקציות באתר, באמצעות עוגיות. המידע מועבר ל־Microsoft. אפשר להמשיך לגלוש גם ללא אישור ולשנות את הבחירה בתחתית העמוד. <a href="https://privacy.microsoft.com/privacystatement" target="_blank" rel="noopener">פרטיות Microsoft</a></p><div class="analytics-actions"><button type="button" data-consent="granted">אישור מדידה</button><button type="button" data-consent="denied">ללא מדידה</button></div>';
  panel.hidden = consent === 'granted' || consent === 'denied';
  document.body.append(panel);
  const preferences = document.createElement('button');
  preferences.type = 'button';
  preferences.className = 'analytics-preferences';
  preferences.textContent = 'העדפות פרטיות ומדידה';
  preferences.addEventListener('click', () => {
   panel.hidden = false;
   panel.querySelector('button').focus();
  });
  document.querySelector('.site-footer')?.append(preferences);
  panel.addEventListener('click', e => {
   const button = e.target.closest('[data-consent]');
   if (!button) return;
   consent = button.dataset.consent;
   try { localStorage.setItem(storageKey, consent); } catch { /* Keep this page's choice. */ }
   panel.hidden = true;
   if (consent === 'granted') start();
   else if (started) {
    window.clarity('consentv2', {analytics_Storage: 'denied', ad_Storage: 'denied'});
    window.clarity('consent', false);
    // Reload without the tracker after withdrawing consent.
    location.reload();
   }
   preferences.focus();
  });
  start();

  // Delegation also covers catalog cards generated by scripts.js.
  // Use fixed action/product IDs; never send link query strings or message text.
  document.addEventListener('click', e => {
   const control = e.target.closest('a, button');
   if (!control) return;
   const product = control.closest('.game-card')?.id.replace(/^game-/, '');
   if (control.matches('.detail-toggle') && control.getAttribute('aria-expanded') === 'true') {
    event('game_details_open_' + product);
   }
   if (control.matches('.gallery .prev, .gallery .next')) event('gallery_manual_' + (product || 'home'));
   if (control.matches('.card-link')) event('game_preview_' + product);
   if (control.matches('#restart-game')) event('sample_game_restart');
   if (control.matches('.online-activities a')) event('online_activity_open');
   if (control.tagName !== 'A') return;
   const url = new URL(control.href, location.href);
   if (url.hostname === 'wa.me' || url.hostname === 'api.whatsapp.com') {
    event(product ? 'order_click_' + product : control.closest('#bundle-offer') ? 'order_click_bundle' : 'contact_whatsapp');
   } else if (url.protocol === 'tel:') event('contact_phone');
   else if (url.protocol === 'mailto:') event('contact_email');
   else if (['www.facebook.com', 'www.instagram.com', 'www.tiktok.com'].includes(url.hostname)) event('social_' + url.hostname.split('.')[1]);
  });
 });
})();
